// ─── Helper ───────────────────────────────────────────────────────────────────

function paginateSkipLimit<T>(items: T[], skip = 0, limit = 25): { items: T[]; total: number; skip: number; limit: number } {
  return {
    items: items.slice(skip, skip + limit),
    total: items.length,
    skip,
    limit,
  };
}

