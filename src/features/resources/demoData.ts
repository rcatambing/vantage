export function listDemoResources(params: ResourcesQueryParams = {}): PaginatedResources {
  let filtered = resources.filter((r) => {
    if (params.resource_type && r.resource_type !== params.resource_type) return false;
    if (params.status && r.status !== params.status) return false;
    if (params.condition && r.condition !== params.condition) return false;
    if (params.office_id && r.current_assignment?.office_id !== params.office_id) return false;
    if (params.unassigned && r.current_assignment !== null) return false;
    if (params.tag && !r.tags.includes(params.tag)) return false;
    if (params.min_value != null && (r.current_value ?? 0) < params.min_value) return false;
    if (params.max_value != null && (r.current_value ?? 0) > params.max_value) return false;
    if (params.maintenance_due) {
      if (!r.next_maintenance_date) return false;
      const due = new Date(r.next_maintenance_date);
      const now = new Date();
      if (due > now) return false;
    }
    if (params.search) {
      const q = params.search.toLowerCase();
      if (
        !r.resource_name.toLowerCase().includes(q) &&
        !(r.resource_code?.toLowerCase().includes(q)) &&
        !(r.brand?.toLowerCase().includes(q)) &&
        !(r.model?.toLowerCase().includes(q))
      ) return false;
    }
    return true;
  });
  return paginateSkipLimit(filtered, params.skip ?? 0, params.limit ?? 25);
}

