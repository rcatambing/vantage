export function unassignDemoResource(resourceId: string, payload: ResourceUnassignPayload = {}): { message: string; data: ResourceAssignment } {
  const idx = resources.findIndex((r) => r.id === resourceId);
  if (idx < 0) throw new Error(`Resource not found: ${resourceId}`);
  const currentAssignment = resources[idx].current_assignment;
  if (!currentAssignment) throw new Error("Resource is not currently assigned.");
  const histIdx = assignmentHistory.findIndex((a) => a.id === currentAssignment.id);
  const now = nowIso();
  if (histIdx >= 0) {
    assignmentHistory[histIdx] = { ...assignmentHistory[histIdx], unassigned_at: now, unassigned_by: "U-001", unassigned_by_name: "Demo User" };
  }
  const updatedAssignment = histIdx >= 0 ? assignmentHistory[histIdx] : {
    ...currentAssignment,
    resource_id: resourceId,
    resource_name: resources[idx].resource_name,
    unassigned_at: now,
    unassigned_by: "U-001",
    unassigned_by_name: "Demo User",
    from_office_id: null,
    from_office_name: null,
    notes: payload.notes ?? null,
  } as ResourceAssignment;
  resources[idx] = { ...resources[idx], status: "AVAILABLE", current_assignment: null, updated_at: now };
  return { message: "Resource unassigned successfully.", data: updatedAssignment };
}

